import frappe
from frappe.query_builder import DocType
from frappe.desk.reportview import get_match_cond

from .stock_graph import require_read, trace

MAX_DEPTH_DEFAULT = 2


@frappe.whitelist()
def trace_batch(batch_no, direction=0, from_datetime=None, to_datetime=None,
                max_depth=MAX_DEPTH_DEFAULT, company=None):
    require_read("Batch", batch_no)
    return trace(company, direction, from_datetime, to_datetime, max_depth, batch_no=batch_no)


@frappe.whitelist()
def trace_warehouse(warehouse, direction=0, from_datetime=None, to_datetime=None,
                    max_depth=MAX_DEPTH_DEFAULT, company=None):
    require_read("Company", company)
    require_read("Warehouse", warehouse)
    if not frappe.get_list("Warehouse", filters={"name": warehouse, "company": company,
                                               "is_group": 0, "disabled": 0}, limit=1):
        frappe.throw("Select an enabled leaf warehouse in the selected company.")
    return trace(company, direction, from_datetime, to_datetime, max_depth, warehouse=warehouse)


@frappe.whitelist()
def search_warehouses(query, company, limit=20):
    require_read("Company", company)
    return _search("Warehouse", query, limit, "warehouse_name", ["name", "warehouse_name"],
                   {"company": company, "is_group": 0, "disabled": 0})


@frappe.whitelist()
def search_batches(query, limit=20):
    """Type-ahead for the batch input. Every whitespace-separated token must
    appear (as a substring) in the batch name or item."""
    return _search("Batch", query, limit, "item", ["name", "item", "batch_qty"], {})


def _search(doctype, query, limit, other_field, fields, filters):
    tokens = str(query or "").strip()[:240].split()
    if not tokens:
        return []
    frappe.has_permission(doctype, "read", throw=True)
    try:
        limit = max(1, min(int(limit or 20), 50))
    except (TypeError, ValueError):
        limit = 20
    table = DocType(doctype)
    qb = frappe.qb.from_(table).select(*[table[field] for field in fields])
    for field, value in filters.items():
        qb = qb.where(table[field] == value)
    for token in tokens:
        like = "%" + token.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"
        qb = qb.where(table.name.like(like) | table[other_field].like(like))
    if doctype == "Batch":
        qb = qb.orderby(table.creation, order=frappe.qb.desc)
    sql, values = qb.orderby(table.name).limit(limit).walk()
    # The appended predicate is generated by Frappe, never supplied by the caller.
    base, order = sql.split(" ORDER BY ", 1)
    return frappe.db.sql(base + (get_match_cond(doctype) or "") + " ORDER BY " + order, values, as_dict=True)
